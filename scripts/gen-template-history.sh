#!/usr/bin/env bash
# Regenerate blueprint-template-history.el: the MD5 of every version of
# every system template that ever existed in the git history, plus the
# working copy.  Run from the repository root before every release (see
# AGENTS.md, "Releasing").  The table lets blueprint-upgrade tell a
# project or user template that is an unmodified older copy (safe to
# update) from one the user customized (diff only).
#
# Keys are "<lang>/<name>" (templates/<lang>/<name>, ADR-003; <name> may
# be snippets/<file>, and strings.org is one of them).  Until
# 0.4.x the templates were flat in templates/ and Italian: their
# versions count as versions of "it/<name>".
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

out=blueprint-template-history.el
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

# Every path a template ever had, as "<git path> <key>".
paths=$( { git log --format= --name-only -- templates/ ; find templates -name '*.org'; } \
           | sed -n -e 's#^\(templates/\)\{0,1\}\([^/]*\.org\)$#templates/\2 it/\2#p' \
                    -e 's#^templates/\([a-z][a-z]\)/\(\(snippets/\)\{0,1\}[^/]*\.org\)$#templates/\1/\2 \1/\2#p' \
           | sort -u )
keys=$(echo "$paths" | cut -d' ' -f2 | sort -u)

{
  cat <<'HEAD'
;;; blueprint-template-history.el --- MD5 of every version of the system templates  -*- lexical-binding:t; -*-
;; SPDX-License-Identifier: MIT

;; Author: kLeZ <julius8774@gmail.com>
;; URL: https://github.com/kLeZ/blueprint.el

;;; Commentary:

;; Generated by scripts/gen-template-history.sh: do not edit by hand.
;; One entry per system template, "<lang>/<name>", with the MD5 of
;; every version of it that ever existed in the history of the
;; package (the flat templates/ of the releases before languages
;; existed count as "it/").  A copy in a project or user template
;; directory whose MD5 is in the list but is not the current one is an
;; unmodified older version; one whose MD5 is not in the list was
;; customized (see `blueprint--template-status').

;;; Code:

(defconst blueprint--template-history
  '(
HEAD
  for key in $keys; do
    hashes=$( for path in $(echo "$paths" | awk -v k="$key" '$2 == k {print $1}'); do
                for c in $(git log --format=%H -- "$path"); do
                  git show "$c:$path" 2>/dev/null | md5sum | cut -d' ' -f1
                done
                if [ -f "$path" ]; then md5sum < "$path" | cut -d' ' -f1; fi
              done | sort -u )
    # A deleted-file commit yields the MD5 of empty input: drop it.
    hashes=$(echo "$hashes" | grep -v '^d41d8cd98f00b204e9800998ecf8427e$' || true)
    [ -z "$hashes" ] && continue
    printf '    ("%s"' "$key"
    for h in $hashes; do printf '\n     "%s"' "$h"; done
    printf ')\n'
  done
  cat <<'TAIL'
    )
  "MD5 of every version of each system template, by \"<lang>/<name>\".
Generated by scripts/gen-template-history.sh from the git history.")

(provide 'blueprint-template-history)
;;; blueprint-template-history.el ends here
TAIL
} > "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "Wrote $out"
