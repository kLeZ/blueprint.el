#!/usr/bin/env bash
# Regenerate blueprint-template-history.el: the MD5 of every version of
# every system template that ever existed in the git history, plus the
# working copy.  Run from the repository root before every release (see
# AGENTS.md, "Releasing").  The table lets blueprint-upgrade tell a
# project or user template that is an unmodified older copy (safe to
# update) from one the user customized (diff only).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

out=blueprint-template-history.el
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

names=$( { git log --format= --name-only -- templates/ ; ls templates; } \
           | sed -n 's#^\(templates/\)\{0,1\}\([^/]*\.org\)$#\2#p' | sort -u )

{
  cat <<'HEAD'
;;; blueprint-template-history.el --- MD5 of every version of the system templates  -*- lexical-binding:t; -*-
;; SPDX-License-Identifier: MIT

;; Author: kLeZ
;; URL: https://github.com/kLeZ/blueprint.el

;;; Commentary:

;; Generated by scripts/gen-template-history.sh: do not edit by hand.
;; One entry per system template, with the MD5 of every version of it
;; that ever existed in the history of the package.  A copy in a
;; project or user template directory whose MD5 is in the list but is
;; not the current one is an unmodified older version; one whose MD5 is
;; not in the list was customized (see `blueprint--template-status').

;;; Code:

(defconst blueprint--template-history
  '(
HEAD
  for name in $names; do
    hashes=$( { for c in $(git log --format=%H -- "templates/$name"); do
                  git show "$c:templates/$name" 2>/dev/null | md5sum | cut -d' ' -f1
                done
                [ -f "templates/$name" ] && md5sum < "templates/$name" | cut -d' ' -f1
              } | sort -u )
    # A deleted-file commit yields the MD5 of empty input: drop it.
    hashes=$(echo "$hashes" | grep -v '^d41d8cd98f00b204e9800998ecf8427e$' || true)
    [ -z "$hashes" ] && continue
    printf '    ("%s"' "$name"
    for h in $hashes; do printf '\n     "%s"' "$h"; done
    printf ')\n'
  done
  cat <<'TAIL'
    )
  "MD5 of every version of each system template, by file name.
Generated by scripts/gen-template-history.sh from the git history.")

(provide 'blueprint-template-history)
;;; blueprint-template-history.el ends here
TAIL
} > "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "Wrote $out"
